// TestVerifyOldSignatures ensures signatures from older library versions
// can still be verified (backward compatibility).
func TestVerifyOldSignatures(t *testing.T) {
	sch := rsa.GetScheme()

	// Load the stored public key
	pubKey, err := sch.UnmarshalPublicKeyWire(testPubKeyWire)
	if err != nil {
		t.Fatalf("Failed to unmarshal stored public key: %v", err)
	}

	connFp := []byte("connFp")
	salt := make([]byte, 32)
	copy(salt, "salt")

	partnerId, err := xx.NewID(pubKey, salt, id.User)
	if err != nil {
		t.Fatalf("NewId error: %v", err)
	}

	// Verify the stored signature still works with the current code
	err = verify(partnerId, pubKey, testSignature, connFp, salt)
	if err != nil {
		t.Fatalf("Failed to verify stored signature (backward compatibility broken): %v", err)
	}
}
